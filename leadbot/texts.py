class TextStore:
    """Current texts: the panel override from the database, otherwise the default."""

    def __init__(self, storage: Any = None):
        self.storage = storage

    def _override(self, key: str) -> Optional[str]:
        if self.storage is None:
            return None
        return self.storage.get_text_override(key)

    def get(self, key: str, **vars: Any) -> str:
        text_def = TEXTS[key]  # unknown key -> KeyError
        value = self._override(key)
        if value is None:
            value = text_def.default
        for name, replacement in vars.items():
            value = value.replace("{" + name + "}", str(replacement))
        return value

    def is_overridden(self, key: str) -> bool:
        if key not in TEXTS:
            raise KeyError(key)
        return self._override(key) is not None
