"""Catalog of every text the bot sends (defaults) and the store that applies panel overrides.

Texts of questions, hints, options and info blocks are taken verbatim from the customer's
PDF (``scenario.pdf``). The PDF lost its emoji on extraction, so emoji are picked by meaning;
the customer can change any of them in the panel. No option caption starts with
``common.mark`` ("✅"): the bot puts it before the chosen option, a caption with its own
"✅" would look chosen.

Key naming: ``<node>.<part>``:
* ``<node>.question`` / ``<node>.hint`` / ``<node>.title`` (short title for the summary
  and the "Исправить" list) / ``<node>.opt.<option>`` (button);
* ``<node>.<option>.prompt`` — the "→ поле" request shown after picking that option;
* ``common.*`` navigation and mechanics, ``err.*`` input errors, ``summary.*`` summary,
  ``lead.*`` / ``owner.*`` the lead sent to the owner.

Placeholders (replaced by ``TextStore.get(key, **vars)`` via ``str.replace``):
``{name}`` in ``thanks.text``; ``{policy}`` in ``privacy.text`` (the engine puts the policy
link there); ``{topic}`` in ``ex_card.header``; ``{value}`` in ``contacts.*`` lines;
``{label}``/``{count}`` in ``sections.cat_selected``; ``{url}`` in ``pr_link.opt.use``;
``{file}``, ``{count}``, ``{id}`` where noted in the label.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Dict, Iterable, List, Literal, Optional, Sequence, Tuple

TextKind = Literal["message", "button", "info", "error", "title"]


@dataclass(frozen=True)
class TextDef:
    key: str
    group: str
    label: str
    default: str
    kind: TextKind


# Panel groups in display order.
GROUPS: List[Tuple[str, str]] = [
    ("start", "Вход и меню"),
    ("new", "Новый сайт"),
    ("promo", "Продвижение"),
    ("redesign", "Доработка"),
    ("final", "Контакты клиента"),
    ("examples", "Примеры"),
    ("contacts", "Связаться"),
    ("summary", "Сводка"),
    ("owner", "Заявка владельцу"),
    ("common", "Кнопки и служебные сообщения"),
    ("errors", "Ошибки ввода"),
    ("info", "Информационные блоки"),
]

TEXTS: Dict[str, TextDef] = {}


def _t(key: str, group: str, label: str, default: str, kind: TextKind = "message") -> None:
    if key in TEXTS:
        raise ValueError(f"duplicate text key {key}")
    TEXTS[key] = TextDef(key=key, group=group, label=label, default=default, kind=kind)


def _node(group: str, node: str, title: str, question: str, hint: Optional[str] = None,
          options: Sequence[Tuple[str, str]] = (),
          prompts: Iterable[Tuple[str, str]] = ()) -> None:
    """Question node: title, question, optional hint, option buttons, "→ поле" prompts.

    ``prompts`` are ``(key suffix, text)``; the key becomes ``<node>.<suffix>``.
    """
    _t(f"{node}.title", group, f"«{title}» — краткий заголовок для сводки", title, "title")
    _t(f"{node}.question", group, f"«{title}» — вопрос", question)
    if hint is not None:
        _t(f"{node}.hint", group, f"«{title}» — подсказка под вопросом", hint)
    for n, (opt, text) in enumerate(options, start=1):
        _t(f"{node}.opt.{opt}", group, f"«{title}» — вариант {n}", text, "button")
    for suffix, text in prompts:
        _t(f"{node}.{suffix}", group, f"«{title}» — запрос ввода ({suffix.split('.')[0]})", text)


